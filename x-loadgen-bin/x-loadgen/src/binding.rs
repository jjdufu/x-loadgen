//! 请求绑定（`x-mazbri-signature*` 头）：配置解析、签名器构造与本地密钥生成。
//!
//! SDK（encrypted 路径）与 plain 路径共用同一个 [`RequestSigner`]，签名逻辑全部在
//! `mazbri-core::crypto::request_binding`，与 gateway 校验同源。

use anyhow::{Context, Result, anyhow, bail};
use base64::Engine;
use base64::engine::general_purpose::STANDARD;
use mazbri_core::crypto::request_binding::{RequestSigner, parse_binding_alg};
use mazbri_core::crypto::{AlgorithmId, AlgorithmKind, generate_sign_keypair};
use serde::Deserialize;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// `[tenant.binding]`：kid + 算法 + 密钥（文件或内联，二选一）。
///
/// - HMAC 算法：密钥文本为 mgmt 创建请求密钥时返回的 `hmacKey`（标准 Base64）。
/// - 签名算法：密钥文本为客户端私钥（PKCS#8 PEM，或 Base64 原始字节）。
#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BindingConfig {
    pub kid: String,
    pub alg: String,
    /// 密钥文件路径；相对路径相对配置文件所在目录。推荐（文件权限 600）。
    #[serde(default)]
    pub key_file: Option<PathBuf>,
    /// 内联密钥文本（仅本地临时测试；不要提交到仓库）。
    #[serde(default)]
    pub key: Option<String>,
}

impl std::fmt::Debug for BindingConfig {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("BindingConfig")
            .field("kid", &self.kid)
            .field("alg", &self.alg)
            .field("key_file", &self.key_file)
            .field("key", &self.key.as_ref().map(|_| "<redacted>"))
            .finish()
    }
}

impl BindingConfig {
    /// 把相对 `key_file` 解析为相对配置文件目录的路径。
    pub fn resolve_paths(&mut self, config_dir: &Path) {
        if let Some(path) = self.key_file.as_mut()
            && path.is_relative()
        {
            *path = config_dir.join(&*path);
        }
    }

    fn key_text(&self) -> Result<String> {
        match (&self.key_file, &self.key) {
            (Some(path), None) => fs::read_to_string(path).with_context(|| {
                format!("failed to read tenant.binding.key_file {}", path.display())
            }),
            (None, Some(inline)) => Ok(inline.clone()),
            (Some(_), Some(_)) => bail!("tenant.binding: set only one of key_file / key"),
            (None, None) => bail!("tenant.binding: key_file or key is required"),
        }
    }

    /// 校验配置并构造签名器（构造时会自检一次签名）。
    pub fn signer(&self) -> Result<RequestSigner> {
        let alg = parse_binding_alg(self.alg.trim())
            .map_err(|_| anyhow!("unsupported tenant.binding.alg={}", self.alg))?;
        let text = self.key_text()?;
        let material = if alg.kind() == AlgorithmKind::Mac {
            STANDARD
                .decode(text.trim())
                .context("tenant.binding HMAC key must be standard base64")?
        } else {
            text.trim().as_bytes().to_vec()
        };
        RequestSigner::new(self.kid.trim(), alg, &material)
            .map_err(|error| anyhow!("invalid tenant.binding key for {}: {error}", alg.as_str()))
    }
}

/// 生成签名密钥对并落盘（私钥 600；公钥用于 mgmt 注册，可公开）。
pub fn keygen(alg: &str, private_out: &Path, public_out: &Path) -> Result<()> {
    let alg: AlgorithmId =
        parse_binding_alg(alg.trim()).map_err(|_| anyhow!("unsupported --alg={alg}"))?;
    if alg.kind() == AlgorithmKind::Mac {
        bail!(
            "HMAC request keys are generated by mgmt (POST /tenants/{{code}}/request-keys); keygen only supports signature algorithms"
        );
    }
    let pair = generate_sign_keypair(alg).map_err(|error| anyhow!("keygen failed: {error}"))?;
    write_private(private_out, pair.private_pem.as_bytes())?;
    fs::write(public_out, pair.public_pem.as_bytes())
        .with_context(|| format!("failed to write {}", public_out.display()))?;
    Ok(())
}

fn write_private(path: &Path, bytes: &[u8]) -> Result<()> {
    let mut options = fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    let mut file = options
        .open(path)
        .with_context(|| format!("failed to create {} (must not exist)", path.display()))?;
    file.write_all(bytes)
        .with_context(|| format!("failed to write {}", path.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use mazbri_core::crypto::AlgorithmRegistry;
    use mazbri_core::crypto::request_binding::{
        SignatureVersion, binding_key_ref, canonical_http_binding, parse_signature_input,
        verify_binding,
    };

    fn temp_dir(tag: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("loadgen-binding-{tag}-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&dir).expect("mkdir");
        dir
    }

    #[test]
    fn keygen_then_signer_verifies_with_public_key_for_every_asym_version() {
        let registry = AlgorithmRegistry::default_registry();
        for version in SignatureVersion::ALL
            .into_iter()
            .filter(|v| !v.is_symmetric())
        {
            let alg = version.default_alg();
            let dir = temp_dir(alg.as_str());
            let private = dir.join("client.key");
            let public = dir.join("client.pub");
            keygen(alg.as_str(), &private, &public).expect("keygen");
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let mode = fs::metadata(&private).expect("meta").permissions().mode() & 0o777;
                assert_eq!(mode, 0o600);
            }
            let mut config = BindingConfig {
                kid: "3".into(),
                alg: alg.as_str().into(),
                key_file: Some(PathBuf::from("client.key")),
                key: None,
            };
            config.resolve_paths(&dir);
            let signer = config.signer().expect("signer");
            let headers = signer
                .sign("POST", mazbri_sdk::GATEWAY_INVOKE_PATH, b"{}")
                .expect("sign");
            assert_eq!(
                parse_signature_input(&headers.signature_input).expect("input"),
                alg
            );
            let public_text = fs::read(&public).expect("public");
            let key = binding_key_ref(alg, &public_text).expect("public key");
            let canonical = canonical_http_binding(
                "POST",
                mazbri_sdk::GATEWAY_INVOKE_PATH,
                headers.timestamp,
                &headers.nonce,
                b"{}",
            );
            verify_binding(&registry, alg, &key, &canonical, &headers.signature)
                .unwrap_or_else(|_| panic!("{version} verify"));
            assert!(
                keygen(alg.as_str(), &private, &public).is_err(),
                "must not overwrite"
            );
            fs::remove_dir_all(&dir).expect("cleanup");
        }
    }

    #[test]
    fn hmac_binding_uses_base64_secret_and_rejects_bad_config() {
        let ok = BindingConfig {
            kid: "1".into(),
            alg: "hmac-sm3".into(),
            key_file: None,
            key: Some(STANDARD.encode([5u8; 32])),
        };
        assert_eq!(ok.signer().expect("signer").alg(), AlgorithmId::HmacSm3);
        assert!(!format!("{ok:?}").contains(&STANDARD.encode([5u8; 32])));
        let bad = [
            BindingConfig {
                alg: "hmac-md5".into(),
                ..ok.clone()
            },
            BindingConfig {
                key: Some("not base64!".into()),
                ..ok.clone()
            },
            BindingConfig {
                key: None,
                ..ok.clone()
            },
            BindingConfig {
                key_file: Some("/nonexistent".into()),
                ..ok.clone()
            },
            BindingConfig {
                alg: "rsa-pkcs1v15-sign-sha256".into(),
                ..ok.clone()
            },
        ];
        for config in bad {
            assert!(config.signer().is_err(), "{config:?}");
        }
        assert!(keygen("hmac-sha256", Path::new("/tmp/x"), Path::new("/tmp/y")).is_err());
    }
}
